"""Build the storyboard art: story/art/cast.svg (the shared symbol sprite), story/art/sheet-*.svg,
story/art/panel-NN.svg (standalone, each carrying the symbols it uses) and story/art/art.js (what index.html inlines;
file:// pages cannot <use> symbols from another file in Chromium).

Run: cd travelos-autopilot && pixi run python docs/design/cover-v2/story/tools/build_art.py
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import cast  # noqa: E402
import sheets  # noqa: E402
import scenes  # noqa: E402

STORY = HERE.parent
ART = STORY / "art"


def wrap(inner, label):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1600 900" role="img" aria-label="{label}" '
            f'preserveAspectRatio="xMidYMid meet">{inner}</svg>')


def used_symbols(svg):
    ids, todo = set(), set(re.findall(r'href="#([\w-]+)"', svg))
    while todo:
        i = todo.pop()
        if i in ids or i not in cast.SYMS:
            continue
        ids.add(i)
        todo |= set(re.findall(r'href="#([\w-]+)"', cast.SYMS[i][1]))
    return sorted(ids)


def standalone(svg):
    defs = "".join(cast.symbol_svg(i) for i in used_symbols(svg))
    return svg.replace('preserveAspectRatio="xMidYMid meet">', f'preserveAspectRatio="xMidYMid meet"><defs>{defs}</defs>', 1)


def main():
    ART.mkdir(exist_ok=True)
    out = {"sheets": {}, "panels": {}}
    out["sheets"]["maya-sam"] = wrap(sheets.maya_sam(), "Character sheet: Maya and Sam")
    out["sheets"]["rosa-tomas"] = wrap(sheets.rosa_tomas(), "Character sheet: Rosa and Tomás")
    for n, (title, fn) in scenes.PANELS.items():
        out["panels"][n] = wrap(fn(f"p{n}-", "page"), f"Scene {n}: {title}")
    sprite = '<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute" aria-hidden="true">' + \
        "".join(cast.symbol_svg(i) for i in sorted(cast.SYMS)) + "</svg>"
    (ART / "cast.svg").write_text(sprite.replace(' width="0" height="0" style="position:absolute"', ""))
    for k, v in out["sheets"].items():
        (ART / f"sheet-{k}.svg").write_text(standalone(v))
    for n, (title, fn) in scenes.PANELS.items():
        (ART / f"panel-{n}.svg").write_text(standalone(wrap(fn(f"p{n}-", "file"), f"Scene {n}: {title}")))
    out["sprite"] = sprite
    (ART / "art.js").write_text("/* generated by tools/build_art.py; do not edit */\nwindow.ART = " + json.dumps(out) + ";\n")
    print(f"symbols {len(cast.SYMS)}, art.js {len((ART / 'art.js').read_text()) // 1024} KB")


if __name__ == "__main__":
    main()
